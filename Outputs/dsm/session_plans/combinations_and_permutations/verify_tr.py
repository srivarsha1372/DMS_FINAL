# Recomputes every count in "DSM : Combinations and Permutations", by brute force where it is small.
from itertools import permutations as P, combinations as C
from math import factorial as f, perm, comb
ok = lambda c, m: print(("OK  " if c else "BAD ") + m)

ok(sorted(''.join(p) for p in P('ABC', 2)) == ['AB', 'AC', 'BA', 'BC', 'CA', 'CB'], "S2 President/Secretary from A,B,C: 6 listed")
ok([set(c) for c in C('ABC', 2)] == [{'A', 'B'}, {'A', 'C'}, {'B', 'C'}], "S3 teams of 2: 3")
ok(len(list(P(range(8), 3))) == 336 and len(list(C(range(10), 3))) == 120, "S5 medals 336, toppings shape")
ok(len([p for p in P('0123456789', 4)]) == 5040 == 10 * 9 * 8 * 7, "S5 PIN no repeats 10x9x8x7")
ok(sorted(''.join(p) for p in P('MPC')) == sorted(['MPC', 'MCP', 'PMC', 'PCM', 'CMP', 'CPM']) and f(4) == 24 and f(5) == 120, "S6 books 6, 24, 120")
ok([f(n) for n in range(8)] == [1, 1, 2, 6, 24, 120, 720, 5040], "S8 factorial table")
ok(f(10) // f(8) == 90 and f(100) // f(98) == 9900 and f(7) // (f(3) * f(4)) == 35 and f(10) == 3628800, "S8 quick check")
ok(8 * 7 * 6 == perm(8, 3) == f(8) // f(5) == 336, "S9/S10 podium 8P3 = 336")
ok(perm(5, 5) == 120 and perm(7, 1) == 7 and perm(9, 0) == 1, "S11 special cases")
ok([perm(5, 2), perm(6, 3), perm(7, 4), perm(10, 3), perm(4, 4)] == [20, 120, 840, 720, 24], "S12 evaluating nPr")
ok(len(list(P(range(7), 4))) == 840 and f(5) == 120, "S13 stage seating 840, band 120")
ok(len(set(P('COMPUTER', 3))) == 336 and len(set(P('MATH'))) == 24, "S14 codes 336, MATH 24")
ok([n for n in range(1, 50) if n * (n - 1) == 56] == [8] and [n for n in range(1, 50) if perm(n, 3) == 120] == [6], "S15 solve n")
pairs = list(P('ABCD', 2)); teams = {frozenset(p) for p in pairs}
ok(len(pairs) == 12 and len(teams) == 6, "S16 4P2 = 12 -> 6 teams")
ok(comb(4, 2) == f(4) // (f(2) * f(2)) == 6, "S17 4C2 = 6")
ok(comb(9, 0) == 1 and comb(7, 1) == 7 and comb(8, 8) == 1, "S18 special cases")
ok([comb(5, 2), comb(6, 3), comb(10, 3), comb(7, 4), comb(12, 5)] == [10, 20, 120, 35, 792] and 12 * 11 * 10 * 9 * 8 // 120 == 792, "S19 evaluating nCr")
ok(len(list(C(range(10), 2))) == 45 and comb(6, 2) == 15 and comb(5, 2) == 10 and comb(4, 2) == 6, "S20 handshakes 45, lines 15")
ok(len(list(C(range(10), 8))) == 45 and comb(52, 5) == 2598960, "S21 questions 45, hands 2,598,960")
ok(perm(5, 3) == comb(5, 3) * f(3) == 60, "S22 5P3 = 10 x 6 = 60")
ok(all(perm(5, r) == comb(5, r) * f(r) for r in range(6)) and [perm(5, r) for r in range(6)] == [1, 5, 20, 60, 120, 120] and [comb(5, r) for r in range(6)] == [1, 5, 10, 10, 5, 1], "S23 table")
ok(all((perm(n, r) == comb(n, r)) == (r <= 1) for n in range(1, 12) for r in range(n + 1)), "S23 equality only when r = 0 or 1")
ok([(n, r) for n in range(1, 30) for r in range(n + 1) if perm(n, r) == 720 and comb(n, r) == 120] == [(10, 3)], "S24 nPr=720, nCr=120 -> n=10, r=3")
ok(comb(6, 2) * 2 == 30 and perm(7, 3) == 210 and 210 // 6 == 35 and perm(8, 4) == 1680 and 1680 // 24 == 70, "S25 rows 1-3")
ok([(n, r) for n in range(1, 30) for r in range(n + 1) if perm(n, r) == 24 and comb(n, r) == 4] == [(4, 3)], "S25 row 4: r = 3, n = 4")
ok([f(6), perm(6, 3), perm(12, 3), perm(20, 3)] == [720, 120, 1320, 6840], "S27 arranging people")
ok([comb(9, 4), comb(12, 5), comb(15, 11), comb(10, 3)] == [126, 792, 1365, 120] and 15 * 14 * 13 * 12 // 24 == 1365, "S28 committees")
ok(comb(8, 3) == 56 and perm(8, 3) == 336 == 56 * 6, "S29 club 56 vs 336")
ok(f(10) // f(8) == 90 and comb(10, 2) == 45, "S30 mistakes")
ok([comb(8, 2), perm(8, 2), perm(9, 4), comb(9, 4), perm(10, 2)] == [28, 56, 3024, 126, 90], "S31 practice")
ok([comb(100, 2), perm(50, 3), comb(20, 3), f(5), comb(1000, 2)] == [4950, 117600, 1140, 120, 499500], "S32 computing")
